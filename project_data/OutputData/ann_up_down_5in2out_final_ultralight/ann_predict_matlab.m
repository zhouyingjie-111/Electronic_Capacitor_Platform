b1 = single([0.1696705222; 0.02489405498; 0.4390397668; 0.6083446145; -0.3166216314; -0.2557561398; -0.2497736514; 0.1562427431]);
x = W1 * x + b1;
x = max(x, 0);

W2 = single([0.7496592999, -1.202109218, 0.02435659617, 0.1187728271, -0.3822227418, 0.7517601252, 0.2391361445, -0.7024710178; -1.255436778, 0.758232832, -0.02873273566, 0.4911384881, 0.04045600817, 0.1531264186, 0.3608704507, 0.09640038013; 0.9711439013, 0.5470541716, -0.8779408932, -1.517678142, 0.2260795236, -0.7308341861, 0.1070659161, 0.0315329209; -0.2877823412, 0.5713500381, -0.2741933763, -0.5424659252, 0.4620094597, 0.2926309407, -0.485681057, 0.8453922868]);
b2 = single([0.5803380013; -0.0871899277; -0.2886894345; -0.1062119007]);
