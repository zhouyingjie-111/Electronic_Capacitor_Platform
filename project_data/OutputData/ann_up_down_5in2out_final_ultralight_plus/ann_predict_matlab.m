function y = ann_predict_matlab(P_peak, T_rise_fall, VC1, VG1, direction_state)
% Output order: y(1)=D_T_given, y(2)=PWM_S_first
% direction_state: 0=UP, 1=DOWN
x_mean = [21.2564106, 5.538462574e-05, 60.07332993, 210.0725098];
x_std  = [1.970525622, 2.394932199e-05, 13.76665688, 14.71982098];
y_mean = [0.3015256524, 0.2408974171];
y_std  = [0.2194908857, 0.1467877179];

p  = (single(P_peak)      - x_mean(1)) / x_std(1);
t  = (single(T_rise_fall) - x_mean(2)) / x_std(2);
vc = (single(VC1)         - x_mean(3)) / x_std(3);
vg = (single(VG1)         - x_mean(4)) / x_std(4);
d = single(direction_state ~= 0);
x = single([p; t; vc; vg; d]);

W1 = single([-0.02974224091, -0.5850991607, 0.4191196859, -0.2137719095, -0.7830085754; 0.0963902697, -0.1237608567, -0.1138727441, 0.4367240071, 0.2964694798; 0.1415951401, -1.437170982, -0.09224680811, -0.8030892015, 0.001406281022; 0.4393209219, -0.2148385793, 0.1979367137, 0.4390294254, -0.9612153769; -0.2424791157, 0.58241117, 0.3072154224, 1.102843881, 0.3733201325; -0.08307575434, -0.9632778764, -0.4869540036, 0.4531228244, -0.2310408652]);
b1 = single([-0.1536468267; -0.001058558701; 0.1164852381; -0.2498456836; 0.06377463788; -0.4690774977]);
x = W1 * x + b1;
x = max(x, 0);

W2 = single([-0.7043591142, 0.6294541359, 0.02382053807, -0.6006456614, 0.06994639337, 0.9812217355; 0.1340839863, 0.5984945297, -0.5545603037, 0.1899566352, 0.44196257, 0.1517929584]);
b2 = single([-0.3875893652; -0.2093640566]);
x = W2 * x + b2;

y = x .* y_std(:) + y_mean(:);
end